"""
TrendPulse Data Models
Dataclasses for the pipeline data flow.
"""
from dataclasses import dataclass, field
from typing import List, Optional
from datetime import datetime


@dataclass
class TrendItem:
    """A single trend fetched from a source."""
    title: str
    description: str
    source: str          # "NewsAPI" | "Reddit" | "HackerNews"
    source_type: str     # "news" | "social_chatter" | "emerging_topic"
    url: str
    timestamp: str = ""

    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = datetime.utcnow().isoformat()

    def to_document(self) -> str:
        return f"{self.title}. {self.description}"

    def to_metadata(self) -> dict:
        return {
            "source": self.source,
            "source_type": self.source_type,
            "url": self.url,
            "title": self.title,
            "timestamp": self.timestamp,
        }

    def to_dict(self) -> dict:
        return {
            "title": self.title,
            "description": self.description,
            "source": self.source,
            "source_type": self.source_type,
            "url": self.url,
            "timestamp": self.timestamp,
        }


@dataclass
class RetrievedPassage:
    """A passage retrieved from ChromaDB with its similarity score."""
    text: str
    source: str
    source_type: str
    url: str
    title: str
    similarity_score: float

    def to_dict(self) -> dict:
        return {
            "text": self.text,
            "source": self.source,
            "source_type": self.source_type,
            "url": self.url,
            "title": self.title,
            "similarity_score": round(self.similarity_score, 4),
        }


@dataclass
class GeneratedContent:
    """Content generated by the RAG pipeline."""
    title: str
    body: str
    citations: List[int] = field(default_factory=list)
    retrieval_scores: List[float] = field(default_factory=list)
    retrieved_passages: List[RetrievedPassage] = field(default_factory=list)
    model: str = "llama-3.3-70b-versatile"
    generated_at: str = ""

    def __post_init__(self):
        if not self.generated_at:
            self.generated_at = datetime.utcnow().isoformat()

    def to_dict(self) -> dict:
        return {
            "title": self.title,
            "body": self.body,
            "citations": self.citations,
            "retrieval_scores": [round(s, 4) for s in self.retrieval_scores],
            "retrieved_passages": [p.to_dict() for p in self.retrieved_passages],
            "model": self.model,
            "generated_at": self.generated_at,
        }


@dataclass
class PostResult:
    """Result of posting content to Reddit."""
    reddit_url: str
    post_id: str
    subreddit: str
    timestamp: str = ""
    success: bool = True
    error: Optional[str] = None

    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = datetime.utcnow().isoformat()

    def to_dict(self) -> dict:
        return {
            "reddit_url": self.reddit_url,
            "post_id": self.post_id,
            "subreddit": self.subreddit,
            "timestamp": self.timestamp,
            "success": self.success,
            "error": self.error,
        }


@dataclass
class SwytchcodeLogEntry:
    """A single Swytchcode execution audit log entry."""
    timestamp: str
    tool_id: str
    status: str      # "success" | "error" | "blocked"
    status_code: int
    latency_ms: int
    details: str = ""

    def to_dict(self) -> dict:
        return {
            "timestamp": self.timestamp,
            "tool_id": self.tool_id,
            "status": self.status,
            "status_code": self.status_code,
            "latency_ms": self.latency_ms,
            "details": self.details,
        }


@dataclass
class PipelineResult:
    """Full pipeline execution result."""
    trends: List[TrendItem] = field(default_factory=list)
    vectors_indexed: int = 0
    generated_content: Optional[GeneratedContent] = None
    post_result: Optional[PostResult] = None
    swytchcode_log: List[SwytchcodeLogEntry] = field(default_factory=list)
    started_at: str = ""
    completed_at: str = ""
    status: str = "pending"

    def to_dict(self) -> dict:
        return {
            "trends_count": len(self.trends),
            "trends": [t.to_dict() for t in self.trends],
            "vectors_indexed": self.vectors_indexed,
            "generated_content": self.generated_content.to_dict() if self.generated_content else None,
            "post_result": self.post_result.to_dict() if self.post_result else None,
            "swytchcode_log": [e.to_dict() for e in self.swytchcode_log],
            "started_at": self.started_at,
            "completed_at": self.completed_at,
            "status": self.status,
        }
